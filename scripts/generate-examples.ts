function exampleSpec(name: string): BotSpec {
  const example = EXAMPLES.find((candidate) => candidate.name === name);
  if (example === undefined) throw new Error(`unknown example: ${name}`);
  return example.spec;
}

export function lockfileName(spec: BotSpec): string {
  return spec.stack === "aiogram" ? "uv.lock" : "bun.lock";
}

/** Formats only files Prettier supports; everything else keeps its generated bytes. */
export async function canonicalize(files: readonly TemplateFile[]): Promise<TemplateFile[]> {
  const formatted: TemplateFile[] = [];
  for (const file of files) {
    if (PRETTIER_EXTENSION[extname(file.path)] !== true) {
      formatted.push(file);
      continue;
    }
    const config = (await prettier.resolveConfig(join(REPO_ROOT, file.path))) ?? {};
    let content: string;
    try {
      content = await prettier.format(file.content, { ...config, filepath: file.path });
    } catch (error) {
      throw new Error(`format failed for ${file.path}: ${String(error)}`, { cause: error });
    }
    formatted.push(content === file.content ? file : { ...file, content });
  }
  return formatted;
}

function manifestFor(base: AurifexManifest, files: readonly TemplateFile[]): AurifexManifest {
  const hashes = files
    .filter((file) => file.path !== MANIFEST_PATH)
    .toSorted((left, right) => (left.path < right.path ? -1 : left.path > right.path ? 1 : 0))
    .map((file) => [file.path, sha256Hex(file.content)] as const);
  return { ...base, files: Object.fromEntries(hashes) };
}

async function walk(directory: string, prefix = ""): Promise<string[]> {
  const entries = await readdir(join(directory, prefix), { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries.toSorted((left, right) =>
    left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
  )) {
    const path = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    if (
      [
        "node_modules",
        ".venv",
        "__pycache__",
        ".pytest_cache",
        ".mypy_cache",
        ".ruff_cache",
        "dist",
      ].includes(entry.name)
    )
      continue;
    if (entry.isDirectory()) files.push(...(await walk(directory, path)));
    else if (entry.isFile()) files.push(path);
  }
  return files;
}

async function snapshot(directory: string): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  for (const path of await walk(directory)) {
    files.set(path, await readFile(join(directory, path), "utf8"));
  }
  return files;
}

export async function readExamples(root = REPO_ROOT): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  for (const { name } of EXAMPLES) {
    for (const [path, content] of await snapshot(join(root, "examples", name))) {
      files.set(`examples/${name}/${path}`, content);
    }
  }
  return files;
}

export interface RenderedExample {
  readonly files: readonly TemplateFile[];
  readonly manifest: AurifexManifest;
}

/**
 * Scaffolds, formats, then hashes the final bytes. Formatting happens before
 * the manifest is written, so a manifest can never describe pre-format bytes.
 */
export async function renderExample(
  name: string,
  destination: string,
  policy: PathPolicy,
): Promise<RenderedExample> {
  const result = await scaffoldBot(
    { destination, spec: exampleSpec(name), overwrite: true },
    { policy, now: () => new Date(GENERATED_AT) },
  );
  if (result.status === "error") throw new Error(`${name}: ${result.error.detail}`);

  const files: TemplateFile[] = [];
  for (const reference of result.value.files) {
    const path = reference.path.slice(destination.length + 1);
    if (path === MANIFEST_PATH || LOCKFILE[path] === true) continue;
    const content = await readFile(join(policy.root, destination, path), "utf8");
    const [formatted] = await canonicalize([{ path, content }]);
    if (formatted === undefined) throw new Error(`${name}: canonicalize returned no file`);
    if (formatted.content !== content) {
      await policy.writeFile(`${destination}/${path}`, formatted.content, { overwrite: true });
    }
    files.push(formatted);
  }

  const manifest = manifestFor(result.value.manifest, files);
  const text = serializeManifest(manifest);
  await policy.writeFile(`${destination}/${MANIFEST_PATH}`, text, { overwrite: true });
  return { files: [...files, { path: MANIFEST_PATH, content: text }], manifest };
}

/** Manual regeneration: writes tracked examples/. Never called by --check. */
export async function generateExamples(root = REPO_ROOT): Promise<readonly string[]> {
  const temp = await mkdtemp(join(tmpdir(), "aurifex-regenerate-"));
  try {
    const tempPolicy = await createPathPolicy(temp);
    const rendered = await Promise.all(
      EXAMPLES.map(async ({ name }) => ({
        name,
        result: await renderExample(name, name, tempPolicy),
      })),
    );
    const policy = await createPathPolicy(root);
    const changed: string[] = [];
    for (const { name, result } of rendered) {
      const prefix = `examples/${name}`;
      const before = await snapshot(join(root, prefix));
      const previous = JSON.parse(before.get(MANIFEST_PATH) ?? '{"files":{}}') as AurifexManifest;
      const expected = new Set(result.files.map((file) => file.path));
      for (const path of Object.keys(previous.files)) {
        if (expected.has(path) || LOCKFILE[path] === true) continue;
        await rm(policy.resolve(`${prefix}/${path}`), { force: true });
        changed.push(`${prefix}/${path}`);
      }
      for (const file of result.files) {
        if (before.get(file.path) === file.content) continue;
        await policy.writeFile(`${prefix}/${file.path}`, file.content, { overwrite: true });
        changed.push(`${prefix}/${file.path}`);
      }
      process.stdout.write(`${name}: ${result.files.length} files\n`);
    }
    return changed;
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
}

export interface ExampleDrift {
  readonly example: string;
  readonly path: string;
  readonly reason: "missing" | "extra" | "changed";
}

/** Read-only parity check: renders into a temp dir, never writes examples/. */
export async function checkExamples(root = REPO_ROOT): Promise<readonly ExampleDrift[]> {
  const temp = await mkdtemp(join(tmpdir(), "aurifex-examples-"));
  const drift: ExampleDrift[] = [];
  try {
    const policy = await createPathPolicy(temp);
    for (const example of EXAMPLES) {
      const rendered = await renderExample(example.name, example.name, policy);
      const expected = new Map(rendered.files.map((file) => [file.path, file.content]));
      const trackedRoot = join(root, "examples", example.name);

      for (const [path, content] of expected) {
        let actual: string;
        try {
          actual = await readFile(join(trackedRoot, path), "utf8");
        } catch {
          drift.push({ example: example.name, path, reason: "missing" });
          continue;
        }
        if (actual !== content) drift.push({ example: example.name, path, reason: "changed" });
      }

      for (const path of await walk(trackedRoot)) {
        if (expected.has(path) || path === MANIFEST_PATH || LOCKFILE[path] === true) continue;
        drift.push({ example: example.name, path, reason: "extra" });
      }

      const lockfile = lockfileName(example.spec);
      try {
        const info = await stat(join(trackedRoot, lockfile));
        if (!info.isFile())
          drift.push({ example: example.name, path: lockfile, reason: "missing" });
      } catch {
        drift.push({ example: example.name, path: lockfile, reason: "missing" });
      }
    }
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
  return drift;
}

export async function runExamples(argv: readonly string[]): Promise<number> {
  if (argv.includes("--check")) {
    const drift = await checkExamples(REPO_ROOT);
    if (drift.length === 0) {
      process.stdout.write("examples: ok\n");
      return 0;
    }
    for (const item of drift) {
      process.stderr.write(`${item.example}/${item.path}: ${item.reason}\n`);
    }
    return 1;
  }
  const changed = await generateExamples(REPO_ROOT);
  process.stdout.write(
    changed.length === 0 ? "examples: unchanged\n" : `examples: ${changed.length} files updated\n`,
  );
  return 0;
}

const entry = process.argv[1];
if (entry !== undefined && realpathSync(entry) === realpathSync(fileURLToPath(import.meta.url))) {
  process.exitCode = await runExamples(process.argv.slice(2));
}
